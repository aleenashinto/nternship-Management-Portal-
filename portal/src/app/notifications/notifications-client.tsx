"use client";

import { useState } from "react";
import { useRouter } from "next/navigation";
import { toast } from "sonner";
import { api } from "@/lib/api-client";

type NotifRow = {
  id: string;
  type: string;
  title: string;
  message: string;
  link: string | null;
  isRead: boolean;
  createdAt: string;
};

export function NotificationsClient({ initial }: { initial: NotifRow[] }) {
  const router = useRouter();
  const [busy, setBusy] = useState(false);

  async function markAllRead() {
    setBusy(true);
    try {
      await api("/api/notifications/read-all", { method: "POST" });
      toast.success("All notifications marked as read");
      router.refresh();
    } catch (err) {
      toast.error((err as Error).message);
    } finally {
      setBusy(false);
    }
  }

  async function markOneRead(n: NotifRow) {
    if (!n.isRead) {
      await api(`/api/notifications/${n.id}/read`, { method: "POST" });
      router.refresh();
    }
    if (n.link) router.push(n.link);
  }

  return (
    <div className="space-y-6">
      <div className="flex flex-wrap items-center justify-between gap-3">
        <div>
          <h1 className="text-2xl font-bold text-gray-900">In-Portal Notification Centre</h1>
          <p className="text-sm text-gray-500">
            All portal alerts and automated email notifications generated by domain events.
          </p>
        </div>
        {initial.some((n) => !n.isRead) && (
          <button
            disabled={busy}
            onClick={markAllRead}
            className="rounded-xl border border-gray-200 px-4 py-2 text-xs font-semibold text-gray-700 hover:bg-gray-50"
          >
            Mark All as Read
          </button>
        )}
      </div>

      <div className="space-y-2">
        {initial.length === 0 && (
          <div className="rounded-2xl border border-gray-100 p-10 text-center text-sm text-gray-400">
            No notifications yet.
          </div>
        )}
        {initial.map((n) => (
          <div
            key={n.id}
            onClick={() => markOneRead(n)}
            className={`cursor-pointer rounded-2xl border p-4 transition ${
              n.isRead ? "border-gray-100 bg-white" : "border-brand-200 bg-brand-50/60"
            }`}
          >
            <div className="flex items-center justify-between gap-2">
              <div className="flex items-center gap-2">
                {!n.isRead && <span className="h-2 w-2 rounded-full bg-brand-600" />}
                <h2 className="text-sm font-bold text-gray-900">{n.title}</h2>
              </div>
              <span className="text-xs text-gray-400">{new Date(n.createdAt).toLocaleString()}</span>
            </div>
            <p className="mt-1 whitespace-pre-line text-xs text-gray-600">{n.message}</p>
          </div>
        ))}
      </div>
    </div>
  );
}
